# -*- coding: utf-8 -*-
"""Final-cut review: transparent evidence-based index, NEVER a viral probability.

The index is a human-interpretable checklist and channel-topic match; it is not
trained or calibrated to predict recommendations, views, or platform algorithms.
"""
from __future__ import annotations
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import json
from pathlib import Path
from channel_audience import AudienceProfile, title_tokens
from viral_studio import Brief, ffmpeg_tools, _probe, ViralStudioError


@dataclass(frozen=True)
class FinalReview:
    index: int
    rating: str
    confidence: str
    matched_videos: int
    historical_range: tuple[int, int] | None
    checks: tuple[dict, ...]
    suggestions: tuple[str, ...]
    limitations: tuple[str, ...]
    actual_seconds: float
    output: str


def evaluate_final_cut(brief: Brief, profile: AudienceProfile, output: Path,
                       *, tools=None, rendered=None) -> FinalReview:
    """Analyze actual MP4 metadata plus storyboard and channel history.

    `rendered` may be trusted metadata generated by render_video for a unit test;
    production always validates the real video with ffprobe.
    """
    output=Path(output)
    if not output.is_file() or output.stat().st_size<1000:
        raise ViralStudioError('Для итоговой оценки необходим настоящий смонтированный MP4')
    if tools is None:
        _, ffprobe=ffmpeg_tools()
    else:
        _,ffprobe=tools
    duration, has_audio = _probe(output,ffprobe)
    if rendered is not None and abs(float(rendered['duration'])-duration)>2:
        raise ViralStudioError('Длительность смонтированного файла не совпадает с монтажным листом')
    topic_words=set(title_tokens(brief.topic))
    comparable=[v.views for v in profile.videos if topic_words & set(title_tokens(v.title))]
    observed=None
    if len(comparable)>=3:
        ordered=sorted(comparable)
        observed=(ordered[max(0,int((len(ordered)-1)*.25))],
                  ordered[min(len(ordered)-1,int((len(ordered)-1)*.75))])
    # Index based on explicit, inspectable criteria, not fitted prediction.
    matches=topic_words & set(profile.successful_topics)
    points=40
    checks=[]
    def add(label,passed,delta,reason):
        nonlocal points
        if passed:
            points+=delta
        checks.append({'check':label,'passed':bool(passed),'impact':delta if passed else 0,'why':reason})
    add('Подтверждённая тема канала',bool(matches),15,
        'Совпадение с повторяющимися словами лидеров' if matches else 'Нет подтверждённого совпадения')
    add('Короткий вертикальный формат', 12<=duration<=60,12,f'Длительность {duration:.1f} с')
    add('Зацепка в первом кадре', bool(brief.shots) and brief.shots[0].seconds<=3.5 and bool(brief.hook.strip()),12,
        'Оценивается только сценарная структура, не реакция людей')
    add('Темп монтажа',len(brief.shots)>=4 and duration/max(1,len(brief.shots))<=8,8,
        f'{len(brief.shots)} сцен; средняя длина {duration/max(1,len(brief.shots)):.1f} с')
    add('Есть аудиодорожка',has_audio,6,'Проверено наличие потока; разборчивость речи не проверена')
    add('Короткие экранные надписи',all(len(s.caption)<=55 for s in brief.shots),4,
        'Проверены тексты сценария, не читаемость пикселей в кадре')
    add('Призыв к действию',bool(brief.call_to_action.strip()),3,'Есть CTA в сценарии')
    index=max(0,min(100,points))
    rating=('хорошее соответствие по формальным признакам' if index>=80 else
            'среднее соответствие; требуется редакторская проверка' if index>=60 else
            'слабое соответствие; нужен пересмотр')
    suggestions=[]
    if not matches:suggestions.append('Проверь соответствие темы интересам аудитории: в лидерах канала эта тема не повторяется.')
    if duration>60:suggestions.append('Сократи вступления и второстепенные сцены; длительность больше 60 секунд.')
    if brief.shots and brief.shots[0].seconds>3.5:suggestions.append('Перенеси демонстрацию результата в первые три секунды.')
    if not has_audio:suggestions.append('Проверь звуковую дорожку и разборчивость голоса.')
    if any(len(s.caption)>55 for s in brief.shots):suggestions.append('Сократи надписи, чтобы их успевали читать с телефона.')
    if not suggestions:suggestions.append('Просмотри ролик вручную на телефоне и протестируй несколько вариантов заголовка.')
    limits=['Индекс 0–100 — эвристическая проверка качества и соответствия каналу, НЕ процент вероятности вирусности.',
            'Просмотры будущего ролика предсказать по этому индексу нельзя.',
            'Оценка не проверяет реальную эмоцию/смысл/динамику каждого кадра или работу рекомендаций.',
            'Данные не включают будущие CTR, удержание, реакции зрителей.']
    if observed is None:limits.append('Меньше 3 похожих прошлых роликов; числовой ориентир по просмотрам не даётся.')
    return FinalReview(index,rating,profile.confidence,len(comparable),observed,
                       tuple(checks),tuple(suggestions),tuple(limits),round(duration,2),str(output))


def save_review(review: FinalReview, project_dir: Path):
    project_dir=Path(project_dir)
    project_dir.mkdir(parents=True,exist_ok=True)
    # Reports belong to the person who may have edited them since the last
    # review. Reassessment must publish a new, bounded numbered pair rather
    # than clobber either the machine report or personal notes.
    json_file=md_file=None
    for version in range(1,102):
        suffix='' if version==1 else f'_V{version}'
        candidate_json=project_dir/f'FINAL_AUDIENCE_REVIEW{suffix}.json'
        candidate_md=project_dir/f'FINAL_AUDIENCE_REVIEW_RU{suffix}.md'
        if not any(p.exists() or p.is_symlink() for p in (candidate_json,candidate_md)):
            json_file,md_file=candidate_json,candidate_md
            break
    if json_file is None:
        raise ViralStudioError('Достигнут предел версий отчёта. Сохрани новый проект.')
    data=asdict(review)
    data['reviewed_utc']=datetime.now(timezone.utc).isoformat()
    lines=['# Последний этап: оценка готового видео для аудитории',
           f'Индекс соответствия: {review.index}/100 — {review.rating}',
           f'Надёжность оценки по объёму данных: {review.confidence}',
           f'Смонтированный файл: {review.output}',
           f'Длительность: {review.actual_seconds:.1f} сек.','',
           '## На что опираемся']
    lines += [f'- {x["check"]}: {"да" if x["passed"] else "нет"}. {x["why"]}' for x in review.checks]
    if review.historical_range is not None:
        lines += ['',f'**Исторический ориентир, НЕ прогноз:** похожие видео канала набирали примерно '
                    f'{review.historical_range[0]}–{review.historical_range[1]} просмотров (середина выборки).']
    lines += ['','## Советы специалиста по удержанию и продвижению',
              *[f'- {x}' for x in review.suggestions], '', '## Ограничения',
              *[f'- {x}' for x in review.limitations]]
    # Exclusive creates also protect a user file created after our preflight.
    # If the second output fails, remove only the first file created here.
    # Exported MP4 and ALL previous report versions stay exactly as they were.
    created=[]
    try:
        with json_file.open('x',encoding='utf-8') as stream:
            created.append(json_file)
            json.dump(data,stream,ensure_ascii=False,indent=2)
        with md_file.open('x',encoding='utf-8') as stream:
            created.append(md_file)
            stream.write('\n'.join(lines)+'\n')
    except BaseException:
        for own in reversed(created):
            try:
                own.unlink()
            except OSError:
                pass
        raise
    return md_file
