def initial_guidance(model_ready: bool) -> str:
    first = (
        "Добро пожаловать! Выбери одну из четырёх задач вверху "
        "или просто напиши свою просьбу в поле снизу и нажми Enter. "
        "Например: «хочу сделать видео о путешествии»."
    )
    if model_ready:
        return first + " Qwen для переписки уже подключена."
    return (
        first + " Для свободного общения и анализа картинок нужна Qwen3-VL: "
        "нажми «СКАЧАТЬ QWEN» и подтверди загрузку. "
        "Создание видео и редактор кода можно открыть и без неё."
    )


def model_hint(model_ready: bool, downloading: bool = False) -> str:
    if downloading:
        return "Qwen загружается. Прогресс ниже; можно нажать «СТОП QWEN»."
    if model_ready:
        return "Qwen подключена · Можно говорить своими словами."
    return "Qwen не подключена · Для общения и изображений нажми «СКАЧАТЬ QWEN»."


def clarification(kind: str) -> str:
    return CLARIFICATIONS.get(kind, "")
