def initial_guidance(model_ready: bool) -> str:
    first = (
        "Добро пожаловать! Выбери одну из четырёх задач вверху "
        "или просто напиши свою просьбу в поле снизу и нажми Enter. "
        "Например: «хочу создать видео»."
    )
    if model_ready:
        return (first + " Qwen3-VL подключена для изображений. "
                "Для отдельного диалога нужна Qwen3:4b, а для сценариев "
                "Gemma3:4b. Их можно проверить через «ИИ ПО ЗАДАЧАМ» "
                "в настройках; модели сами не скачиваются.")
    return (
        first + " Для изображений нужна Qwen3-VL: нажми "
        "«СКАЧАТЬ QWEN» и подтверди загрузку. "
        "Для обычного диалога нужна отдельная Qwen3:4b, "
        "для сценариев — Gemma3:4b. Открой «ИИ ПО ЗАДАЧАМ» "
        "в настройках для их установки. Редакторы можно открыть без моделей."
    )


def model_hint(model_ready: bool, downloading: bool = False) -> str:
    if downloading:
        return "Qwen загружается. Прогресс ниже; можно нажать «СТОП QWEN»."
    if model_ready:
        return ("Qwen3-VL подключена для изображений · "
                "Для отдельного диалога нужна Qwen3:4b («ИИ ПО ЗАДАЧАМ»).")
    return ("Qwen3-VL не подключена · «СКАЧАТЬ QWEN» — для изображений; "
            "отдельная Qwen3:4b для диалога — в «ИИ ПО ЗАДАЧАМ».")


def clarification(kind: str) -> str:
    return CLARIFICATIONS.get(kind, "")
